#include <iostream>
using namespace std;

int main() {

    // This is a single-line comment.
    // The compiler ignores everything written after //.
    cout << "Hello, C++!" << endl;

    /*
        This is a multi-line comment.

        You can write multiple lines inside
        opening and closing comment markers

        Multi line comments are useful when
        you need to explain something in detail.
    */

    cout << "I am learning C++ step by step." << endl;

    return 0;
}
